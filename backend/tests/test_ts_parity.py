"""The Python costing engine and sheet parsers must give the same results as the
original TypeScript code (fixtures generated by scripts/generate_ts_golden.ts)."""
import json
import math
from pathlib import Path

import pytest

from app.http import _sanitize
from app.services import costing, sheet_parser

GOLDEN = json.loads((Path(__file__).parent / "fixtures" / "ts_golden.json").read_text(encoding="utf-8"))


def assert_same(expected, actual, path="$"):
    if isinstance(expected, dict):
        assert isinstance(actual, dict), f"{path}: expected object, got {actual!r}"
        assert set(expected) == set(actual), f"{path}: keys differ {set(expected) ^ set(actual)}"
        for k in expected:
            assert_same(expected[k], actual[k], f"{path}.{k}")
    elif isinstance(expected, list):
        assert isinstance(actual, list) and len(expected) == len(actual), f"{path}: list differs"
        for i, (e, a) in enumerate(zip(expected, actual)):
            assert_same(e, a, f"{path}[{i}]")
    elif isinstance(expected, (int, float)) and not isinstance(expected, bool):
        assert isinstance(actual, (int, float)) and not isinstance(actual, bool), f"{path}: {actual!r} is not a number"
        assert math.isclose(expected, actual, rel_tol=1e-12, abs_tol=1e-9), f"{path}: {expected} != {actual}"
    else:
        assert expected == actual, f"{path}: {expected!r} != {actual!r}"


@pytest.mark.parametrize("case", GOLDEN["costing"], ids=lambda c: json.dumps(c["input"])[:60])
def test_calculate_costing_matches_typescript(case):
    out = _sanitize(costing.calculate_costing(case["input"]))
    out["fx"].pop("rate_date")
    assert_same(case["output"], out)


@pytest.mark.parametrize("case", GOLDEN["yarnEngine"], ids=lambda c: json.dumps(c["input"])[:60])
def test_cotton_yarn_engine_matches_typescript(case):
    out = _sanitize(costing.calculate_cotton_yarn_costing(case["input"]))
    out["fx"].pop("rate_date")
    assert_same(case["output"], out)


@pytest.mark.parametrize("case", GOLDEN["freightRates"], ids=lambda c: f"{c['origin']}->{c['destination']}")
def test_freight_rate_lookup_matches_typescript(case):
    assert_same(case["output"], costing.get_freight_rate("COTTON", case["origin"], case["destination"]))


def test_destinations_and_origins_match_typescript():
    assert_same(GOLDEN["destinations"]["Maharashtra"], costing.get_freight_destinations("COTTON", "Maharashtra"))
    assert_same(GOLDEN["destinations"]["all"], costing.get_freight_destinations("COTTON"))
    assert_same(GOLDEN["origins"], costing.get_freight_origins("COTTON"))


@pytest.mark.parametrize(
    "name,parser",
    [
        ("matrix", sheet_parser.parse_google_sheet_yarn_csv),
        ("flat", sheet_parser.parse_google_sheet_yarn_csv),
        ("fob", sheet_parser.parse_google_sheet_fob_csv),
        ("freight", sheet_parser.parse_google_sheet_freight_csv),
    ],
)
def test_sheet_parsers_match_typescript(name, parser):
    case = GOLDEN["parsers"][name]
    assert_same(case["output"], parser(case["csv"]))
